//! Regenerates src/consts.rs: Poseidon round constants, MDS matrix and the
//! empty-subtree roots, so the contract never derives them at run time.
//! Run: cargo run -p antumbra-core --bin gen-consts --release

use antumbra_core::{encoding::fr_to_bytes, poseidon, tree, Fr};
use std::{fs, path::PathBuf};

fn arr(x: &Fr) -> String {
    let b = fr_to_bytes(x);
    let items: Vec<String> = b.iter().map(|v| format!("{v:#04x}")).collect();
    format!("[{}]", items.join(", "))
}

fn main() {
    let cfg = poseidon::generate_config();
    let mut out = String::new();
    out.push_str(
        "//! GENERATED by `cargo run -p antumbra-core --bin gen-consts --release`. Do not edit.\n",
    );
    out.push_str("//! Poseidon (BLS12-381 Fr, width 3, 8 full + 57 partial rounds, alpha 5) and\n");
    out.push_str("//! the empty-subtree roots of the commitment tree. All values are canonical\n");
    out.push_str("//! 32-byte little-endian field elements.\n\n");
    out.push_str(&format!(
        "pub const POSEIDON_ARK: [[[u8; 32]; 3]; {}] = [\n",
        cfg.ark.len()
    ));
    for row in &cfg.ark {
        out.push_str(&format!(
            "    [{}],\n",
            row.iter().map(arr).collect::<Vec<_>>().join(", ")
        ));
    }
    out.push_str("];\n\n");
    out.push_str("pub const POSEIDON_MDS: [[[u8; 32]; 3]; 3] = [\n");
    for row in &cfg.mds {
        out.push_str(&format!(
            "    [{}],\n",
            row.iter().map(arr).collect::<Vec<_>>().join(", ")
        ));
    }
    out.push_str("];\n\n");
    let zeros = tree::compute_zeros_with(&cfg);
    out.push_str(&format!(
        "pub const TREE_ZEROS: [[u8; 32]; {}] = [\n",
        zeros.len()
    ));
    for z in &zeros {
        out.push_str(&format!("    {},\n", arr(z)));
    }
    out.push_str("];\n");
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/consts.rs");
    fs::write(&path, out).unwrap();
    println!("wrote {}", path.display());
}
